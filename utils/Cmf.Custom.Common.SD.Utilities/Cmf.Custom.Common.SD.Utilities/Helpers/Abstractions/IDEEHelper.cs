using Cmf.Custom.Common.SD.Utilities.DataStructures;
using Cmf.Foundation.BusinessObjects.Abstractions;
using Cmf.Foundation.BusinessOrchestration;
using Cmf.Navigo.BusinessObjects.Abstractions;
using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Reflection;

namespace Cmf.Custom.Common.SD.Utilities.Helpers.Abstractions
{
    /// <summary>
    /// This is a utility class for DEE Actions.
    /// </summary>
    public interface IDEEHelper
    {
        #region Action Group

        /// <summary>
        /// Checks if current action group (present in Input dictionary) is valid based on a list of given action groups.
        /// </summary>
        /// <param name="Input">Dictionary where in theory action group is defined.</param>
        /// <param name="ValidActionGroups">List of valid action groups.</param>
        /// <param name="defaultBehavior">Default behavior of method. Defaults to false but can be changed by invoker.</param>
        /// <returns>Returns true if the current action group is valid, false otherwise</returns>
        bool IsActionGroupValid(Dictionary<string, object> Input, Collection<string> ValidActionGroups, bool defaultBehavior = false);

        /// <summary>
        /// This method retrieves the action group from the correspondent input. This assumes it always has one.
        /// </summary>
        /// <param name="Input">The input dictionary with the action group.</param>
        /// <returns>Return the action group name related with the provided input.</returns>
        string GetActionGroup(Dictionary<string, object> Input);

        /// <summary>
        /// This methods dynamically executes the action provided given the input, returning the output
        /// </summary>
        /// <param name="actionName">The action name (to be used as a DEE Input).</param>
        /// <param name="input">The input (to be used on the execution of the action).</param>
        /// <returns>Returns a dictionary with the output generated by executing the DEE.</returns>
        Dictionary<string, object> ExecuteAction(string actionName, Dictionary<string, object> input);



        #endregion Action Group

        #region Service Context

        /// <summary>
        /// Stores the current service info in the transaction context.
        /// Also sets the Initial service context if this is the first context being set in the transaction.
        /// </summary>
        /// <param name="deeRuleName">Current DEE rule name.</param>
        /// <param name="skipInitialContext">Set to true to avoid setting the context as Initial DEE Context, even if this was the first context of the transaction. Is false by default.</param>
        /// <returns>The stored service context (provided it is valid).</returns>
        DeeContext SetCurrentServiceContext(string deeRuleName, bool skipInitialContext = false);

        /// <summary>
        /// Retrieves the current service entry that called the rule in the current transaction.
        /// Requires that the rule previously called SetCurrentServiceContext.
        /// </summary>
        /// <param name="deeRuleName">Current DEE rule name.</param>
        /// <returns>The context for first service that called the rule, or null if CurrentServiceContext was not set.</returns>
        DeeContext GetCurrentServiceContext(string deeRuleName);

        /// <summary>
        /// Retrieves the first service entry that called the rule in the current transaction.
        /// Requires that the rule previously called SetCurrentServiceContext.
        /// </summary>
        /// <param name="deeRuleName">Current DEE rule name.</param>
        /// <returns>The context for first service that called the rule, or null if CurrentServiceContext was not set.</returns>
        DeeContext GetInitialServiceContext(string deeRuleName);

        /// <summary>
        /// Retrieves service comments from the history object.
        /// </summary>
        /// <remarks>Attention: at service level, comments are written after pre actions, so this method will not work.</remarks>
        /// <returns>Service comments, or null if no call context can be found. </returns>
        String GetServiceComments();

        #endregion Service Context

        #region Parameters

        /// <summary>
        /// Stores a value in the current Transaction context.
        /// </summary>
        /// <param name="key">Context key name where to store the value.</param>
        /// <param name="value">Value to store.</param>
        void SetContextParameter(string key, object value);

        /// <summary>
        /// Retrieves a value from the current Transaction context.
        /// </summary>
        /// <param name="key">Context key name where the value is stored.</param>
        /// <returns>Value stored with the given key, null otherwise.</returns>
        [Obsolete(message: "Prefer using generic version GetContextParameter<T>(string key) instead")]
        object GetContextParameter(string key);

        /// <summary>
        /// Retrieves a value from the current Transaction context.
        /// </summary>
        /// <typeparam name="T">Type of the value to be retrieved</typeparam>
        /// <param name="key">Context key name where the value is stored.</param>
        /// <returns>Value of the given <paramref name="key"/> value converted to <typeparamref name="T"/> taken from the current Transaction context, or default(<typeparamref name="T"/>) if key is not found</returns>
        T GetContextParameter<T>(string key);

        #endregion Parameters

        #region Generic

        /// <summary>
        /// Searches and returns a Material from a DEE Input Dictionary.
        /// </summary>
        /// <param name="deeInput">DEE parameters Input Dictionary.</param>
        /// <param name="isInPreconditionCheck">Flag that should be sent as true if inside Dee pre-condition code (can be useful for debugging).</param>
        /// <param name="skipServiceInputs">Set to true to skip search in service Input (Cmf.Foundation.BusinessOrchestration.BaseInput) classes.</param>
        /// <param name="skipServiceOutputs">Set to true to skip search in service Output (Cmf.Foundation.BusinessOrchestration.BaseOutput) classes.</param>
        /// <param name="skipOperations">Set to true to skip search in standard operation parameters.</param>
        /// <param name="loadShallowObjects">Flag to indicate if Material should be reloaded if it's not filled out.</param>
        /// <param name="searchDepth">Max recursivity depth to search through objects</param>
        /// <returns>The first Material object inside the structure, or null if not found.</returns>
        IMaterial GetMaterialFromDeeInput(Dictionary<string, object> deeInput, bool isInPreconditionCheck = false, bool skipServiceInputs = false, bool skipServiceOutputs = false, bool skipOperations = false, bool loadShallowObjects = true, int searchDepth = 10);

        /// <summary>
        /// Searches and returns an Object from a DEE Input Dictionary.
        /// </summary>
        /// <param name="deeInput">DEE parameters Input Dictionary.</param>
        /// <param name="skipServiceInputs">Set to true to skip search in service Input (Cmf.Foundation.BusinessOrchestration.BaseInput) classes.</param>
        /// <param name="skipServiceOutputs">Set to true to skip search in service Output (Cmf.Foundation.BusinessOrchestration.BaseOutput) classes.</param>
        /// <param name="skipOperations">Set to true to skip search in standard operation parameters.</param>
        /// <param name="searchDepth">Max recursivity depth to search through objects.</param>
        /// <returns>The first object instance inside the structure, or null if not found.</returns>
        T GetObjectFromDeeInput<T>(Dictionary<string, object> deeInput, bool skipServiceInputs = false, bool skipServiceOutputs = false, bool skipOperations = false, int searchDepth = 10) where T : class;

        /// <summary>
        /// Searches for an object inside a complex object structure.
        /// </summary>
        /// <typeparam name="T">Type of the object to search for.</typeparam>
        /// <param name="objStructure">Object structure where to search for.</param>
        /// <param name="propertyNames">Property Names to search for (if not sent, it will search for the first instance of type 'T').</param>
        /// <param name="searchDepth">Max recursivity depth to search through objects</param>
        /// <returns>The first occurence of the object inside the structure, or null if not found.</returns>
        T GetObjectFromStructure<T>(dynamic objStructure, string[] propertyNames = null, int searchDepth = 10) where T : class;

        /// <summary>
        /// Gets the calling Service's Comments from the DEE Input dictionary.
        /// </summary>
        /// <param name="deeInput">DEE Input dictionary.</param>
        /// <returns>Service's Input Comments, or null if not found.</returns>
        string GetServiceComments(Dictionary<string, object> deeInput);









        /// <summary>
        /// Determines the resulting attributes validity.
        /// </summary>
        /// <param name="originalAttrs">Attribute values to be resolved.</param>
        /// <param name="serviceInput">The service from which the attributes will be read.</param>
        /// <returns>An AttributeCollection with the resolved final attributes.</returns>
        IAttributeCollection ResolveFinalAttributeValues(IAttributeCollection originalAttrs, BaseInput serviceInput);

        /// <summary>
        /// Extracts the Attributes to update from a standard Service input structure.
        /// </summary>
        /// <param name="serviceInput">Service input structure.</param>
        /// <returns>The Attributes to update, or an empty collection if no attributes are found.</returns>
        IAttributeCollection GetUpdatedAttributes(BaseInput serviceInput);

        /// <summary>
        /// Extracts the attribute names to remove from a standard service input structure
        /// </summary>
        /// <param name="serviceInput">Service input structure</param>
        /// <returns>The names of attributes to remove, or an empty collection if no attributes are found</returns>
        Collection<string> GetRemovedAttributeNames(BaseInput serviceInput);

        /// <summary>
        /// Extracts the attribute names to update or remove from a standard service input structure.
        /// </summary>
        /// <param name="serviceInput">Service input structure.</param>
        /// <returns>The names of attributes to update or remove, or an empty collection if no attributes are found.</returns>
        Collection<string> GetUpdatedAndRemovedAttributeNames(BaseInput serviceInput);





        #endregion Generic







    }
}
